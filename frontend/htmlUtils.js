// htmlUtils.js – shared HTML escaping utility
// ---------------------------------------------------
// Simple, pure function that escapes the characters & < > " ' to safe HTML entities.
export function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
